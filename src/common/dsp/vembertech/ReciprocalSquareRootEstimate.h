inline float reciprocalSquareRootEstimate(float value)
{
    if (!(value > 0.f) || !std::isfinite(value))
        return 1.f / std::sqrt(value);
    uint32_t bits;
    std::memcpy(&bits, &value, sizeof(bits));
    const int exponent = (bits >> 23) & 255;
    if (exponent == 0)
        return reciprocalSquareRootEstimate(value * 16777216.f) * 4096.f;
    const int base = (exponent & 1) ? 127 : 128;
    const int index = ((exponent & 1) ? 0 : 256) + ((bits & 0x7fffff) >> 15);
    bits = reciprocalSquareRootTable[index] - (exponent - base) / 2 * 0x800000;
    float result;
    std::memcpy(&result, &bits, sizeof(result));
    return result;
}
