inline float vocoderEnvelopeRoot(float value)
{
    // Envelope energy is nonnegative. Handle zero and exceptional values
    // explicitly; normal values only need a table read and exponent adjustment.
    if (!(value > 0.f) || !std::isfinite(value))
        return std::sqrt(value);
    uint32_t bits;
    std::memcpy(&bits, &value, sizeof(bits));
    int exponent = (bits >> 23) & 255;
    if (exponent == 0)
        return vocoderEnvelopeRoot(value * 16777216.f) * (1.f / 4096.f);
    const int base = (exponent & 1) ? 127 : 128;
    const int index = ((exponent & 1) ? 0 : 256) + ((bits & 0x7fffff) >> 15);
    bits = vocoderEnvelopeTable[index] + (exponent - base) / 2 * 0x800000;
    float result;
    std::memcpy(&result, &bits, sizeof(result));
    return result;
}
